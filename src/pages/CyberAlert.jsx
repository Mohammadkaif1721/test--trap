
import { useEffect, useState } from "react";
import {
  Bell,
  ShieldAlert,
  FileDown,
  Share2,
  Trash2,
  RefreshCw,
  AlertTriangle,
  CheckCircle,
} from "lucide-react";
import { jsPDF } from "jspdf";
import { supabase } from "../lib/supabase";
import "./CyberAlert.css";

const categories = [
  "Phishing",
  "Scam Message",
  "Malicious URL",
  "Code Vulnerability",
  "Suspicious Activity",
];

const severities = ["Low", "Medium", "High", "Critical"];

export default function CyberAlert() {
  const [alerts, setAlerts] = useState([]);
  const [loading, setLoading] = useState(true);
  const [saving, setSaving] = useState(false);
  const [error, setError] = useState("");
  const [success, setSuccess] = useState("");

  const [form, setForm] = useState({
    title: "",
    category: "Phishing",
    severity: "Medium",
    description: "",
    evidence: "",
  });

  async function loadAlerts() {
    setLoading(true);
    setError("");

    try {
      const { data: userData, error: userError } =
        await supabase.auth.getUser();

      if (userError) throw userError;

      if (!userData.user) {
        throw new Error("Please login to view alerts.");
      }

      const { data, error: queryError } = await supabase
        .from("cyber_alerts")
        .select("*")
        .order("created_at", { ascending: false });

      if (queryError) throw queryError;

      setAlerts(data || []);
    } catch (err) {
      setError(err.message || "Failed to load alerts.");
    } finally {
      setLoading(false);
    }
  }

  useEffect(() => {
    loadAlerts();
  }, []);

  function handleChange(event) {
    const { name, value } = event.target;

    setForm((previous) => ({
      ...previous,
      [name]: value,
    }));
  }

  async function createAlert(event) {
    event.preventDefault();
    setSaving(true);
    setError("");
    setSuccess("");

    try {
      const { data: userData, error: userError } =
        await supabase.auth.getUser();

      if (userError) throw userError;

      if (!userData.user) {
        throw new Error("Please login first.");
      }

      const alertData = {
        user_id: userData.user.id,
        title: form.title.trim(),
        category: form.category,
        severity: form.severity,
        description: form.description.trim(),
        evidence: form.evidence.trim() || null,
      };

      const { data, error: insertError } = await supabase
        .from("cyber_alerts")
        .insert(alertData)
        .select()
        .single();

      if (insertError) throw insertError;

      setAlerts((previous) => [data, ...previous]);

      setForm({
        title: "",
        category: "Phishing",
        severity: "Medium",
        description: "",
        evidence: "",
      });

      setSuccess("Cyber Alert created successfully.");
    } catch (err) {
      setError(err.message || "Unable to create alert.");
    } finally {
      setSaving(false);
    }
  }

  function generatePDF(alert) {
    const pdf = new jsPDF();

    pdf.setFillColor(8, 8, 8);
    pdf.rect(0, 0, 210, 297, "F");

    pdf.setTextColor(220, 20, 60);
    pdf.setFontSize(22);
    pdf.text("TEST TRAP", 20, 25);

    pdf.setTextColor(255, 255, 255);
    pdf.setFontSize(16);
    pdf.text("CYBER ALERT REPORT", 20, 40);

    pdf.setDrawColor(220, 20, 60);
    pdf.line(20, 47, 190, 47);

    pdf.setFontSize(12);
    pdf.setTextColor(220, 220, 220);

    let y = 62;

    const addField = (label, value) => {
      pdf.setTextColor(220, 20, 60);
      pdf.text(label, 20, y);
      y += 7;

      pdf.setTextColor(255, 255, 255);

      const lines = pdf.splitTextToSize(
        String(value || "Not provided"),
        170
      );

      pdf.text(lines, 20, y);
      y += lines.length * 7 + 8;
    };

    addField("Alert ID", alert.id);
    addField("Title", alert.title);
    addField("Category", alert.category);
    addField("Severity", alert.severity);
    addField("Created At", new Date(alert.created_at).toLocaleString());
    addField("Description", alert.description);
    addField("Evidence", alert.evidence);

    pdf.setTextColor(150, 150, 150);
    pdf.setFontSize(9);
    pdf.text(
      "Generated by Test Trap. This report is user-submitted and does not independently verify a threat.",
      20,
      280,
      { maxWidth: 170 }
    );

    pdf.save(`TestTrap-CyberAlert-${alert.id.slice(0, 8)}.pdf`);
  }

  function shareWhatsApp(alert) {
    const text = `TEST TRAP CYBER ALERT

Title: ${alert.title}
Category: ${alert.category}
Severity: ${alert.severity}

Description:
${alert.description}

Evidence:
${alert.evidence || "Not provided"}

Alert ID: ${alert.id}

Please verify this activity before interacting with suspicious links or messages.`;

    const url = `https://wa.me/?text=${encodeURIComponent(text)}`;

    window.open(url, "_blank", "noopener,noreferrer");
  }

  async function deleteAlert(id) {
    const confirmed = window.confirm(
      "Are you sure you want to delete this alert?"
    );

    if (!confirmed) return;

    setError("");
    setSuccess("");

    try {
      const { error: deleteError } = await supabase
        .from("cyber_alerts")
        .delete()
        .eq("id", id);

      if (deleteError) throw deleteError;

      setAlerts((previous) =>
        previous.filter((alert) => alert.id !== id)
      );

      setSuccess("Alert deleted successfully.");
    } catch (err) {
      setError(err.message || "Failed to delete alert.");
    }
  }

  return (
    <main className="cyber-alert-page">
      <header className="cyber-alert-header">
        <div className="cyber-alert-icon">
          <ShieldAlert size={35} />
        </div>

        <h1>Cyber Alert</h1>

        <p>
          Create, document, and share cybersecurity threat reports.
        </p>
      </header>

      <section className="cyber-alert-form-card">
        <div className="cyber-alert-section-title">
          <Bell size={22} />
          <h2>Create New Alert</h2>
        </div>

        <form onSubmit={createAlert}>
          <div className="cyber-alert-form-grid">
            <div className="cyber-alert-field">
              <label htmlFor="title">Alert Title *</label>
              <input
                id="title"
                name="title"
                value={form.title}
                onChange={handleChange}
                placeholder="Example: Suspicious bank message"
                required
                maxLength={150}
              />
            </div>

            <div className="cyber-alert-field">
              <label htmlFor="category">Category *</label>
              <select
                id="category"
                name="category"
                value={form.category}
                onChange={handleChange}
                required
              >
                {categories.map((category) => (
                  <option key={category} value={category}>
                    {category}
                  </option>
                ))}
              </select>
            </div>

            <div className="cyber-alert-field">
              <label htmlFor="severity">Severity *</label>
              <select
                id="severity"
                name="severity"
                value={form.severity}
                onChange={handleChange}
                required
              >
                {severities.map((severity) => (
                  <option key={severity} value={severity}>
                    {severity}
                  </option>
                ))}
              </select>
            </div>

            <div className="cyber-alert-field full-width">
              <label htmlFor="description">Alert Description *</label>
              <textarea
                id="description"
                name="description"
                value={form.description}
                onChange={handleChange}
                placeholder="Explain what happened and why it is suspicious..."
                required
                maxLength={5000}
              />
            </div>

            <div className="cyber-alert-field full-width">
              <label htmlFor="evidence">Evidence / Suspicious URL / Message</label>
              <textarea
                id="evidence"
                name="evidence"
                value={form.evidence}
                onChange={handleChange}
                placeholder="Paste evidence here (optional)..."
                maxLength={10000}
              />
            </div>
          </div>

          {error && (
            <div className="cyber-alert-message error">
              <AlertTriangle size={17} />
              {error}
            </div>
          )}

          {success && (
            <div className="cyber-alert-message success">
              <CheckCircle size={17} />
              {success}
            </div>
          )}

          <button
            type="submit"
            className="cyber-alert-submit"
            disabled={saving}
          >
            <Bell size={18} />
            {saving ? "Creating Alert..." : "Create Cyber Alert"}
          </button>
        </form>
      </section>

      <section className="cyber-alert-history">
        <div className="cyber-alert-section-title history-heading">
          <h2>Alert History</h2>

          <button
            className="cyber-alert-refresh"
            onClick={loadAlerts}
            disabled={loading}
            type="button"
          >
            <RefreshCw size={16} />
            Refresh
          </button>
        </div>

        {loading ? (
          <p className="cyber-alert-empty">Loading alerts...</p>
        ) : alerts.length === 0 ? (
          <p className="cyber-alert-empty">
            No alerts created yet. Create your first Cyber Alert above.
          </p>
        ) : (
          <div className="cyber-alert-list">
            {alerts.map((alert) => (
              <article className="cyber-alert-item" key={alert.id}>
                <div className="cyber-alert-item-top">
                  <div>
                    <span
                      className={`severity-badge severity-${alert.severity.toLowerCase()}`}
                    >
                      {alert.severity}
                    </span>

                    <span className="category-badge">
                      {alert.category}
                    </span>
                  </div>

                  <span className="cyber-alert-date">
                    {new Date(alert.created_at).toLocaleString()}
                  </span>
                </div>

                <h3>{alert.title}</h3>
                <p className="cyber-alert-description">
                  {alert.description}
                </p>

                {alert.evidence && (
                  <details className="cyber-alert-evidence">
                    <summary>View Evidence</summary>
                    <pre>{alert.evidence}</pre>
                  </details>
                )}

                <div className="cyber-alert-actions">
                  <button
                    type="button"
                    onClick={() => generatePDF(alert)}
                  >
                    <FileDown size={16} />
                    Download PDF
                  </button>

                  <button
                    type="button"
                    onClick={() => shareWhatsApp(alert)}
                  >
                    <Share2 size={16} />
                    Share WhatsApp
                  </button>

                  <button
                    type="button"
                    className="delete-alert-btn"
                    onClick={() => deleteAlert(alert.id)}
                  >
                    <Trash2 size={16} />
                    Delete
                  </button>
                </div>
              </article>
            ))}
          </div>
        )}
      </section>
    </main>
  );
}
